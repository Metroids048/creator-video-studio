"""lrc_clip.py <song.lrc> --start=S --end=E [--bpm=B --beat=T0] [--out=src/lyrics.js]

Turns the song's LRC into the MV's lyric table in CLIP time (clip 0 = song time S), the format src/karaoke.js reads:
  const LY = [[start, end, '歌词', { sing: seconds }], …];
end = next line's start (lines butt so the karaoke bar never flashes empty); sing ≈ how long the words take,
capped below the gap. With --bpm/--beat (from beat_grid.py) it also prints each line's beat index, so the clip start
and every shot change can sit on a bar line. Credits/metadata lines (作词/作曲/编曲…) are dropped.
Check the result by ear-proxy: in the 10-second preview the fill must start when the singer does.
"""
import json
import re
import sys
from pathlib import Path

argv = [a for a in sys.argv[1:] if not a.startswith('--')]
opt = dict((a[2:].split('=', 1) + [True])[:2] for a in sys.argv[1:] if a.startswith('--'))
if not argv or 'start' not in opt:
    sys.exit(__doc__)
S, E = float(opt['start']), float(opt.get('end', 1e9))
rows = []
for line in Path(argv[0]).read_text(encoding='utf-8').splitlines():
    for m in re.finditer(r'\[(\d+):(\d+(?:\.\d+)?)\]', line):
        txt = re.sub(r'\[.*?\]', '', line).strip()
        if txt and not re.match(r'^(作词|作曲|编曲|制作|监制|混音|母带|和声|吉他|贝斯|鼓|录音|出品|OP|SP|Produced|Lyrics|Composer)\s*[:：]', txt):
            rows.append((int(m[1]) * 60 + float(m[2]), txt))
rows.sort()
LY = []
for i, (t, txt) in enumerate(rows):
    nxt = rows[i + 1][0] if i + 1 < len(rows) else t + 6
    if t < S - .2 or t >= E - 1.0:   # a line that starts in the last second would only flash
        continue
    a, b = round(t - S, 2), round(min(nxt, E) - S, 2)
    sing = round(min((b - a) * .88, max(1.2, len(txt) * .32)), 2)
    LY.append((a, b, txt, sing))

if 'bpm' in opt and 'beat' in opt:
    B, t0 = 60 / float(opt['bpm']), float(opt['beat'])
    for a, b, txt, _ in LY:
        print(f'{a:7.2f}  beat {(a + S - t0) / B:7.2f}  {txt}')
body = ',\n'.join(f"  [{a:.2f}, {b:.2f}, {json.dumps(txt, ensure_ascii=False)}, {{ sing: {s:.2f} }}]" for a, b, txt, s in LY)
js = f'// lyrics.js — generated by lrc_clip.py from {Path(argv[0]).name}, clip start {S}s. Edit freely; times are clip time.\nconst LY = [\n{body},\n];\n'
o = Path(opt.get('out', 'src/lyrics.js'))
o.parent.mkdir(parents=True, exist_ok=True)
o.write_text(js, encoding='utf-8')
print(f'LYRICS_DONE {len(LY)} lines → {o}')

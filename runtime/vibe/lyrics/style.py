"""style.py — one place that decides a film's lettering: font, sizes, colours. Every text-drawing step reads its output.

  style.py list                                   presets (kit/styles/*.json) with their use
  style.py <preset> --project=DIR [--type=T]      resolve and write DIR/style.json (Python tools) and the page's
                                                  style.js (lyric-mv: DIR/src/style.js, knowledge-short: DIR/film/style.js)
  style.py <preset> --json                        print the resolved style

Sizes are set by measured GLYPH HEIGHT (kit/styles/_targets.json, px) and converted per renderer with the font's
measured metrics (kit/styles/_metrics.json, from font_metrics.py): libass, ffmpeg drawtext and canvas all draw the same
font size at different heights (Ma Shan Zheng 0.64 / 0.87; ZCOOL KuaiLe 0.82 / 0.88). Guessing from the font size made a
"small" title bigger than the lyrics twice in 挪威的森林.
The user's standing call (2026-10-24): subtitles smaller than v10's (lyric ≈60 px tall on a 1080×1920 screen, not 83),
and a characterful display font chosen to fit the film — decided once here, never per file.
"""
import json
import shutil
import sys
from pathlib import Path

KIT = Path(__file__).resolve().parent.parent
SD = KIT / 'styles'
DEFAULT = {'lyric-mv': 'cute', 'knowledge-short': 'modern'}


def presets():
    return {p.stem: json.loads(p.read_text(encoding='utf-8')) for p in sorted(SD.glob('[!_]*.json'))}


def resolve(name):
    ps = presets()
    if name not in ps:
        sys.exit(f'unknown style "{name}" — one of: {", ".join(ps)}')
    p, tg = ps[name], json.loads((SD / '_targets.json').read_text(encoding='utf-8'))
    for k, v in p.get('targets', {}).items():
        tg[k].update(v)
    m = json.loads((SD / '_metrics.json').read_text(encoding='utf-8')).get(p['font'])
    if not m:
        sys.exit(f'no metrics for {p["font"]} — run: kit/lyrics/font_metrics.py {KIT / "fonts" / p["font"]}')
    px = lambda h: round(h / m['pxH'])                         # canvas / drawtext font size for a glyph height
    ass = round(tg['vertical']['lyric'] / m['assH'])
    return {
        'name': name, 'desc': p['desc'], 'family': m['family'], 'file': str(KIT / 'fonts' / p['font']),
        'fontFile': p['font'], 'fallback': p['fallback'], 'colors': p['colors'], 'stroke': p['stroke'], 'shadow': p['shadow'],
        'targets': tg,
        'canvas': {k: px(v) for k, v in tg['canvas'].items()},
        'drawtext': {'vTitle': px(tg['vertical']['title']), 'vArtist': px(tg['vertical']['artist']),
                     **{f'cover_{k}': px(v) for k, v in tg['cover'].items()}},
        'ass': {'lyric': ass, 'adv': round(m['assAdv'] * ass + 6, 1), 'maxw': round(1080 * tg['vertical']['maxRowFrac'])},
    }


def write(name, proj, typ):
    st = resolve(name)
    proj = Path(proj).resolve()
    (proj / 'style.json').write_text(json.dumps(st, ensure_ascii=False, indent=1), encoding='utf-8')
    page_dir, url = (proj / 'film', '../assets/fonts/') if typ == 'knowledge-short' else (proj / 'src', 'assets/fonts/')
    fonts = proj / 'assets/fonts'
    if not fonts.exists():
        fonts.parent.mkdir(parents=True, exist_ok=True)
        fonts.symlink_to(KIT / 'fonts')
    elif not fonts.is_symlink() and not (fonts / st['fontFile']).exists():
        shutil.copy2(st['file'], fonts / st['fontFile'])       # an older project with its own fonts dir
    js = {k: st[k] for k in ('name', 'family', 'fallback', 'colors', 'stroke', 'shadow', 'canvas')}
    js['css'] = f'"{st["family"]}", {st["fallback"]}'
    js['fontUrl'] = url + st['fontFile']
    page_dir.mkdir(parents=True, exist_ok=True)
    (page_dir / 'style.js').write_text(
        f'// style.js — generated by kit/lyrics/style.py (preset "{name}": {st["desc"]}).\n'
        f'// Switch the whole film\'s lettering with `./vf style <preset>`; don\'t edit by hand.\n'
        f'window.STYLE = {json.dumps(js, ensure_ascii=False)};\n'
        '(() => { const f = new FontFace(STYLE.family, `url("${STYLE.fontUrl}")`); document.fonts.add(f); STYLE.fontReady = f.load().catch(e => console.error("style font failed", e)); })();\n',
        encoding='utf-8')
    print(f'STYLE_DONE {name} ({st["family"]}) → {proj / "style.json"}, {page_dir / "style.js"}  '
          f'[canvas karaoke {st["canvas"]["karaoke"]}px, vertical lyric ASS {st["ass"]["lyric"]}]')


if __name__ == '__main__':
    argv = [a for a in sys.argv[1:] if not a.startswith('--')]
    opt = dict((a[2:].split('=', 1) + [True])[:2] for a in sys.argv[1:] if a.startswith('--'))
    if not argv or argv[0] == 'list':
        for k, v in presets().items():
            print(f'{k:10s} {v["desc"]}  ({", ".join(v["for"])})')
        sys.exit(0)
    if opt.get('json'):
        print(json.dumps(resolve(argv[0]), ensure_ascii=False, indent=1))
    else:
        write(argv[0], opt.get('project', '.'), opt.get('type', 'lyric-mv'))
